package traduce

import (
	"archive/zip"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

func elencoAlbero(t *testing.T, d string) []string {
	var out []string
	_ = filepath.Walk(d, func(p string, info os.FileInfo, err error) error {
		rel, _ := filepath.Rel(d, p)
		if rel != "." {
			out = append(out, rel)
		}
		return nil
	})
	sort.Strings(out)
	return out
}

func zipDiProva(t *testing.T, p string, file map[string]string) {
	f, err := os.Create(p)
	if err != nil {
		t.Fatal(err)
	}
	z := zip.NewWriter(f)
	for n, c := range file {
		w, _ := z.Create(n)
		w.Write([]byte(c))
	}
	z.Close()
	f.Close()
}

func TestModGiocoInstallaETogli(t *testing.T) {
	app, gioco := t.TempDir(), t.TempDir()
	os.MkdirAll(filepath.Join(gioco, "Gioco_Data", "il2cpp_data"), 0o755)
	os.WriteFile(filepath.Join(gioco, "Gioco.exe"), []byte("exe"), 0o644)
	os.WriteFile(filepath.Join(gioco, "GameAssembly.dll"), []byte("ga"), 0o644)
	os.WriteFile(filepath.Join(gioco, "changelog.txt"), []byte("del gioco"), 0o644) // esiste già: va salvato
	prima := elencoAlbero(t, gioco)

	if tipo, exe := TipoUnity(gioco); tipo != "il2cpp" || exe != "Gioco.exe" {
		t.Fatalf("tipo %q exe %q", tipo, exe)
	}
	z1, z2 := filepath.Join(app, "a.zip"), filepath.Join(app, "b.zip")
	zipDiProva(t, z1, map[string]string{"winhttp.dll": "w", "changelog.txt": "di bepinex", "BepInEx/core/x.dll": "x", "dotnet/y.dll": "y"})
	zipDiProva(t, z2, map[string]string{
		"BepInEx/plugins/XUnity.AutoTranslator/Translators/GoogleTranslate.dll":          "no",
		"BepInEx/plugins/XUnity.AutoTranslator/Translators/CustomTranslate.dll":          "si",
		"BepInEx/plugins/XUnity.AutoTranslator/Translators/FullNET/Http.ExtProtocol.dll": "no",
		"../fuori.txt": "x",
	})
	// lo zip con un percorso fuori dalla cartella del gioco deve essere rifiutato e tutto tolto
	if _, err := InstallaModGioco(app, "Gioco", gioco, "gioco", []string{z1, z2}, "en", "it"); err == nil {
		t.Fatal("zip con ../ accettato")
	}
	if dopo := elencoAlbero(t, gioco); strings.Join(dopo, "|") != strings.Join(prima, "|") {
		t.Fatalf("dopo il rifiuto il gioco non è com'era:\n%v\n%v", prima, dopo)
	}
	if b, _ := os.ReadFile(filepath.Join(gioco, "changelog.txt")); string(b) != "del gioco" {
		t.Fatalf("originale non rimesso: %q", b)
	}

	zipDiProva(t, z2, map[string]string{
		"BepInEx/plugins/XUnity.AutoTranslator/Translators/GoogleTranslate.dll":          "no",
		"BepInEx/plugins/XUnity.AutoTranslator/Translators/CustomTranslate.dll":          "si",
		"BepInEx/plugins/XUnity.AutoTranslator/Translators/FullNET/Http.ExtProtocol.dll": "no",
	})
	m, err := InstallaModGioco(app, "Gioco", gioco, "gioco", []string{z1, z2}, "en", "it")
	if err != nil {
		t.Fatal(err)
	}
	if esisteFile(filepath.Join(gioco, "BepInEx/plugins/XUnity.AutoTranslator/Translators/GoogleTranslate.dll")) ||
		esisteFile(filepath.Join(gioco, "BepInEx/plugins/XUnity.AutoTranslator/Translators/FullNET/Http.ExtProtocol.dll")) {
		t.Fatal("installato un traduttore in rete")
	}
	if !esisteFile(filepath.Join(gioco, "BepInEx/plugins/XUnity.AutoTranslator/Translators/CustomTranslate.dll")) {
		t.Fatal("manca CustomTranslate")
	}
	cfg, _ := os.ReadFile(filepath.Join(gioco, "BepInEx/config/AutoTranslatorConfig.ini"))
	if !strings.Contains(string(cfg), "Url=http://127.0.0.1:47321/gioco/gioco/"+m.Token) || !strings.Contains(string(cfg), "Endpoint=CustomTranslate") || len(m.Token) != 32 {
		t.Fatalf("config: %s", cfg)
	}
	if len(m.Sostituiti) != 0 {
		t.Fatalf("changelog degli strumenti non deve coprire quello del gioco: %v", m.Sostituiti)
	}
	if _, err := InstallaModGioco(app, "Gioco", gioco, "gioco", []string{z1, z2}, "en", "it"); err == nil {
		t.Fatal("seconda installazione accettata")
	}
	if ModGiaPresenti(gioco) == "" {
		t.Fatal("dopo l'installazione le mod devono risultare presenti")
	}
	// il gioco lascia delle traduzioni: Ferma le tiene da parte e le rimette la volta dopo
	tr := filepath.Join(gioco, "BepInEx/Translation/it/Text")
	os.MkdirAll(tr, 0o755)
	os.WriteFile(filepath.Join(tr, "_AutoGeneratedTranslations.txt"), []byte("Iron helmet=Elmo ferro\nA\\=B=A\\=B tradotto\n"), 0o644)
	n, err := CorreggiFileXUnity(filepath.Join(tr, "_AutoGeneratedTranslations.txt"), map[string][2]string{"Iron helmet": {"Elmo ferro", "Elmo di ferro"}, "A=B": {"A=B tradotto", "A=B giusto"}})
	if err != nil || n != 2 {
		t.Fatalf("correzioni %d %v", n, err)
	}
	b, _ := os.ReadFile(filepath.Join(tr, "_AutoGeneratedTranslations.txt"))
	if string(b) != "Iron helmet=Elmo di ferro\nA\\=B=A\\=B giusto\n" {
		t.Fatalf("file corretto: %q", b)
	}

	if err := TogliModGioco(app, "gioco"); err != nil {
		t.Fatal(err)
	}
	if dopo := elencoAlbero(t, gioco); strings.Join(dopo, "|") != strings.Join(prima, "|") {
		t.Fatalf("dopo Ferma il gioco non è com'era:\n%v\n%v", prima, dopo)
	}
	if b, _ := os.ReadFile(filepath.Join(gioco, "changelog.txt")); string(b) != "del gioco" {
		t.Fatalf("originale non rimesso: %q", b)
	}
	if _, err := InstallaModGioco(app, "Gioco", gioco, "gioco", []string{z1, z2}, "en", "it"); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(filepath.Join(tr, "_AutoGeneratedTranslations.txt")); !strings.Contains(string(b), "Elmo di ferro") {
		t.Fatal("traduzioni della volta prima non rimesse")
	}
	TogliModGioco(app, "gioco")
	if dopo := elencoAlbero(t, gioco); strings.Join(dopo, "|") != strings.Join(prima, "|") {
		t.Fatalf("seconda volta: %v", dopo)
	}
}
